-- =====================================================
-- TABLAS PRINCIPALES
-- =====================================================

CREATE TABLE ciudad (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    departamento  VARCHAR(100) NOT NULL,
    poblacion     INTEGER,
    CONSTRAINT uq_ciudad_nombre_depto UNIQUE (nombre, departamento),
    CONSTRAINT ck_ciudad_poblacion CHECK (poblacion IS NULL OR poblacion >= 0)
);

CREATE TABLE estacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    codigo      VARCHAR(30)  NOT NULL,
    ubicacion   VARCHAR(255),
    estado      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVA',
    ciudad_id   BIGINT       NOT NULL,
    CONSTRAINT uq_estacion_codigo UNIQUE (codigo),
    CONSTRAINT ck_estacion_estado CHECK (estado IN ('ACTIVA', 'INACTIVA', 'MANTENIMIENTO')),
    CONSTRAINT fk_estacion_ciudad FOREIGN KEY (ciudad_id)
        REFERENCES ciudad (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Relacion 1:1 con estacion (la FK es UNIQUE)
CREATE TABLE configuracion_estacion (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estacion_id             BIGINT NOT NULL,
    intervalo_medicion_min  INTEGER NOT NULL DEFAULT 10,
    umbral_temp_max         NUMERIC(5,2),
    umbral_presion_min      NUMERIC(7,2),
    CONSTRAINT uq_config_estacion UNIQUE (estacion_id),
    CONSTRAINT ck_config_intervalo CHECK (intervalo_medicion_min > 0),
    CONSTRAINT fk_config_estacion FOREIGN KEY (estacion_id)
        REFERENCES estacion (id) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE registro_clima (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temperatura  NUMERIC(5,2) NOT NULL,
    humedad      NUMERIC(5,2) NOT NULL,
    presion      NUMERIC(7,2) NOT NULL,
    fecha        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estacion_id  BIGINT       NOT NULL,
    CONSTRAINT ck_registro_humedad CHECK (humedad BETWEEN 0 AND 100),
    CONSTRAINT ck_registro_presion CHECK (presion > 0),
    CONSTRAINT fk_registro_estacion FOREIGN KEY (estacion_id)
        REFERENCES estacion (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tipo_medicion (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(50) NOT NULL,
    unidad       VARCHAR(20) NOT NULL,
    descripcion  VARCHAR(255),
    CONSTRAINT uq_tipo_medicion_nombre UNIQUE (nombre)
);

CREATE TABLE alerta (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion        VARCHAR(255) NOT NULL,
    nivel              VARCHAR(10)  NOT NULL,
    fecha              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado             VARCHAR(10)  NOT NULL DEFAULT 'ACTIVA',
    registro_clima_id  BIGINT       NOT NULL,
    CONSTRAINT ck_alerta_nivel  CHECK (nivel IN ('BAJO', 'MEDIO', 'ALTO')),
    CONSTRAINT ck_alerta_estado CHECK (estado IN ('ACTIVA', 'RESUELTA')),
    CONSTRAINT fk_alerta_registro FOREIGN KEY (registro_clima_id)
        REFERENCES registro_clima (id) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    correo      VARCHAR(150) NOT NULL,
    contrasena  VARCHAR(255) NOT NULL,
    CONSTRAINT uq_usuario_correo UNIQUE (correo)
);

CREATE TABLE rol (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(50) NOT NULL,
    descripcion  VARCHAR(255),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre)
);

-- =====================================================
-- TABLAS INTERMEDIAS (relaciones N:M)
-- =====================================================

-- Usuario N:M Rol
CREATE TABLE usuario_rol (
    usuario_id  BIGINT NOT NULL,
    rol_id      BIGINT NOT NULL,
    PRIMARY KEY (usuario_id, rol_id),
    CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuario (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (rol_id)
        REFERENCES rol (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- RegistroClima N:M TipoMedicion
CREATE TABLE registro_tipo_medicion (
    registro_clima_id  BIGINT NOT NULL,
    tipo_medicion_id   BIGINT NOT NULL,
    PRIMARY KEY (registro_clima_id, tipo_medicion_id),
    CONSTRAINT fk_rtm_registro FOREIGN KEY (registro_clima_id)
        REFERENCES registro_clima (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_rtm_tipo FOREIGN KEY (tipo_medicion_id)
        REFERENCES tipo_medicion (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- =====================================================
-- INDICES (PostgreSQL no indexa las FK automaticamente)
-- =====================================================

CREATE INDEX idx_estacion_ciudad      ON estacion (ciudad_id);
CREATE INDEX idx_registro_estacion    ON registro_clima (estacion_id);
CREATE INDEX idx_registro_fecha       ON registro_clima (fecha);
CREATE INDEX idx_registro_temperatura ON registro_clima (temperatura);
CREATE INDEX idx_alerta_registro      ON alerta (registro_clima_id);
CREATE INDEX idx_alerta_nivel_estado  ON alerta (nivel, estado);
CREATE INDEX idx_usuario_rol_rol      ON usuario_rol (rol_id);
CREATE INDEX idx_rtm_tipo             ON registro_tipo_medicion (tipo_medicion_id);

